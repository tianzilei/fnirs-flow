# Reportlets: subject/session/run granularity
# ============================================================================


def generate_subject_reportlet(
    subject: str,
    runs: list[dict[str, Any]],
    outdir: Path,
) -> Path:
    """Generate a subject-level reportlet."""
    subject = _sanitize_bids_label(subject, "subject")
    lines = [
        f"# Subject Report: {subject}",
        "",
        f"**Generated:** {datetime.now(timezone.utc).isoformat()}",
        f"**Total runs:** {len(runs)}",
        "",
        "## Run Summary",
        "",
        "| Session | Run | Status | Steps |",
        "|---------|-----|--------|-------|",
    ]
    for r in runs:
        lines.append(
            f"| {r.get('session', '')} | {r.get('run', '')} | "
            f"{r.get('status', '')} | {len(r.get('steps_completed', []))} |"
        )
    lines.append("")

    subject_dir = outdir / f"sub-{subject}"
    subject_dir.mkdir(parents=True, exist_ok=True)
    path = subject_dir / f"sub-{subject}_desc-subject_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def generate_session_reportlet(
    subject: str,
    session: str,
    runs: list[dict[str, Any]],
    outdir: Path,
) -> Path:
    """Generate a session-level reportlet."""
    subject = _sanitize_bids_label(subject, "subject")
    session = _sanitize_bids_label(session, "session")
    lines = [
        f"# Session Report: {subject} / {session}",
        "",
        f"**Generated:** {datetime.now(timezone.utc).isoformat()}",
        f"**Total runs:** {len(runs)}",
        "",
        "## Runs",
        "",
        "| Run | Status | Steps |",
        "|-----|--------|-------|",
    ]
    for r in runs:
        lines.append(f"| {r.get('run', '')} | {r.get('status', '')} | {len(r.get('steps_completed', []))} |")
    lines.append("")

    session_dir = outdir / f"sub-{subject}" / f"ses-{session}"
    session_dir.mkdir(parents=True, exist_ok=True)
    path = session_dir / f"sub-{subject}_ses-{session}_desc-session_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def generate_run_reportlet(
    subject: str,
    session: str,
    run: str,
    run_data: dict[str, Any],
    outdir: Path,
) -> Path:
    """Generate a run-level reportlet."""
    subject = _sanitize_bids_label(subject, "subject")
    session = _sanitize_bids_label(session, "session")
    run = _sanitize_bids_label(run, "run")
    lines = [
        f"# Run Report: {subject} / {session} / {run}",
        "",
        f"**Generated:** {datetime.now(timezone.utc).isoformat()}",
        f"**Status:** {run_data.get('status', 'unknown')}",
        "",
        "## Steps Completed",
        "",
    ]
    for step in run_data.get("steps_completed", []):
        lines.append(f"- {step}")

    if run_data.get("errors"):
        lines.extend(["", "## Errors", ""])
        for err in run_data["errors"]:
            lines.append(f"- {err}")

    lines.append("")

    run_dir = outdir / f"sub-{subject}" / f"ses-{session}" / f"run-{run}"
    run_dir.mkdir(parents=True, exist_ok=True)
    path = run_dir / f"sub-{subject}_ses-{session}_run-{run}_desc-run_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def generate_all_reportlets(
    planned_runs: list[dict[str, Any]],
    outdir: Path,
) -> list[Path]:
    """Generate subject/session/run reportlets for all planned runs.

    Groups runs by subject and session, then generates:
    - One subject-level reportlet per subject
    - One session-level reportlet per subject/session
    - One run-level reportlet per run

    Returns list of generated report paths.
    """
    # Group by subject, then by session
    by_subject: dict[str, list[dict[str, Any]]] = {}
    by_session: dict[tuple[str, str], list[dict[str, Any]]] = {}

    for run in planned_runs:
        subj = run.get("subject", "")
        sess = run.get("session", "")
        by_subject.setdefault(subj, []).append(run)
        by_session.setdefault((subj, sess), []).append(run)

    paths: list[Path] = []

    # Subject reportlets
    for subj, runs in by_subject.items():
        if subj:
            paths.append(generate_subject_reportlet(subj, runs, outdir))

    # Session reportlets
    for (subj, sess), runs in by_session.items():
        if subj and sess:
            paths.append(generate_session_reportlet(subj, sess, runs, outdir))

    # Run reportlets
    for run in planned_runs:
        subj = run.get("subject", "")
        sess = run.get("session", "")
        run_name = run.get("run", "")
        if subj and sess and run_name:
            paths.append(generate_run_reportlet(subj, sess, run_name, run, outdir))

    return paths
