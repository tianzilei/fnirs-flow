"""Report generators: analysis plan, validation, citation, run reports, and reportlets."""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

_BIDS_LABEL_RE = re.compile(r"^[a-zA-Z0-9_-]+$")


def _sanitize_bids_label(value: str, label_name: str) -> str:
    """Validate and sanitize a BIDS label (subject/session/run) to prevent path traversal."""
    if not value or not _BIDS_LABEL_RE.match(value):
        raise ValueError(f"Invalid {label_name} '{value}': must match [a-zA-Z0-9_-]+")
    return value


def generate_analysis_plan(plan: dict[str, Any], outdir: Path) -> Path:
    """Generate analysis_plan.md from compiled plan."""
    lines = [
        "# fNIRS Analysis Plan",
        "",
        f"**Flow ID:** {plan.get('flow_id', 'N/A')}",
        f"**Name:** {plan.get('name', 'N/A')}",
        f"**Description:** {plan.get('description', 'N/A')}",
        "",
        "## Preprocessing Chain",
        "",
    ]

    for step in plan.get("preprocessing_atoms", []):
        lines.append(f"- **{step.get('atom_id', 'N/A')}** ({step.get('atom_type', 'N/A')})")
        if step.get("parameters"):
            lines.append(f"  - Parameters: `{json.dumps(step['parameters'])}`")

    lines.extend(
        [
            "",
            "## Analysis Chain",
            "",
        ]
    )

    for step in plan.get("analysis_atoms", []):
        lines.append(f"- **{step.get('atom_id', 'N/A')}** ({step.get('atom_type', 'N/A')})")
        if step.get("parameters"):
            lines.append(f"  - Parameters: `{json.dumps(step['parameters'])}`")

    lines.extend(
        [
            "",
            "## Execution",
            "",
            f"- Total steps: {plan.get('execution', {}).get('total_steps', 'N/A')}",
            f"- Flow ID: {plan.get('flow_id', 'N/A')}",
            "",
            f"*Generated by fnirs-flow on {datetime.now(timezone.utc).isoformat()}*",
        ]
    )

    path = outdir / "analysis_plan.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def generate_validation_report(
    errors: list[str],
    warnings: list[str],
    risks: list[dict[str, Any]],
    outdir: Path,
) -> Path:
    """Generate validation_report.md."""
    lines = [
        "# Validation Report",
        "",
        f"**Generated:** {datetime.now(timezone.utc).isoformat()}",
        "",
    ]

    if errors:
        lines.append(f"## Errors ({len(errors)})")
        lines.append("")
        for e in errors:
            lines.append(f"- {e}")
        lines.append("")

    if warnings:
        lines.append(f"## Warnings ({len(warnings)})")
        lines.append("")
        for w in warnings:
            lines.append(f"- {w}")
        lines.append("")

    if risks:
        lines.append(f"## Risks ({len(risks)})")
        lines.append("")
        for r in risks:
            severity = r.get("severity", "unknown")
            lines.append(f"- [{severity}] {r.get('message', '')}")
        lines.append("")
    else:
        lines.append("## Risks\n\nNo risks identified.\n")

    path = outdir / "validation_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def generate_run_report(
    batch_summary: dict[str, Any],
    outdir: Path,
) -> Path:
    """Generate run_report.md from batch execution results."""
    lines = [
        "# Run Report",
        "",
        f"**Generated:** {datetime.now(timezone.utc).isoformat()}",
        "",
        "## Summary",
        "",
        f"- Total runs: {batch_summary.get('total', 0)}",
        f"- Successful: {batch_summary.get('successful', 0)}",
        f"- Failed: {batch_summary.get('failed', 0)}",
        "",
    ]

    failed_ids = batch_summary.get("failure_ids", [])
    if failed_ids:
        lines.append("## Failed Runs")
        lines.append("")
        for fid in failed_ids:
            lines.append(f"- {fid}")
        lines.append("")

    path = outdir / "run_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


